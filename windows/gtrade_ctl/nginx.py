"""nginx front door: TLS termination, SPA, /static, /media, reverse proxy to Waitress.

Only nginx listens on the network. Waitress (127.0.0.1:8001) and PostgreSQL (127.0.0.1:5544)
stay on loopback, so a LAN Server needs exactly one inbound firewall rule.

* Standalone binds 127.0.0.1 only; LAN Server binds all interfaces (firewall restricts to the
  Private profile / local subnet).
* Plain HTTP is not served at all; there is no port 80 listener to downgrade to.
* ``/media/`` is proxied through Django rather than served as a static alias, so uploaded files
  keep whatever access rules the application applies (audit finding: /media was public).
"""

from __future__ import annotations

from pathlib import Path

SECURITY_HEADERS = {
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'SAMEORIGIN',
    'Referrer-Policy': 'same-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
    # Print previews (bills, labels) render inline <script> in same-origin popups, which inherit
    # this policy, so script-src cannot drop 'unsafe-inline' without breaking printing. The rest
    # of the policy still blocks plugins, foreign frames, base-tag hijack and off-site form posts.
    'Content-Security-Policy': ("default-src 'self'; script-src 'self' 'unsafe-inline'; "
                                "style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; "
                                "font-src 'self' data:; connect-src 'self'; object-src 'none'; "
                                "base-uri 'self'; form-action 'self'; frame-ancestors 'self'"),
    'Strict-Transport-Security': 'max-age=31536000',
}


def _q(p: Path | str) -> str:
    # nginx on Windows accepts forward slashes; quote for paths with spaces.
    return '"' + str(p).replace('\\', '/') + '"'


def ipv6_loopback_available() -> bool:
    """True when this PC can bind the IPv6 loopback (::1). Windows resolves "localhost" to ::1
    first and a connect to a closed ::1 port is refused only after ~2 s (SYN retries), so without an
    [::1] listener every new connection to https://localhost pays that wait (Chromium races IPv4
    after ~0.2-0.3 s; Python/.NET clients wait the full 2 s). PCs with IPv6 removed keep IPv4 only."""
    import socket
    try:
        s = socket.socket(socket.AF_INET6, socket.SOCK_STREAM)
    except OSError:
        return False
    try:
        s.bind(('::1', 0))
        return True
    except OSError:
        return False
    finally:
        s.close()


def render(*, listen_host: str, https_port: int, app_port: int, spa_root: Path, static_root: Path,
           tls_dir: Path, logs_dir: Path, temp_dir: Path, max_body_mb: int = 1100,
           ipv6_loopback: bool = False) -> str:
    headers = '\n'.join(f'    add_header {k} "{v}" always;' for k, v in SECURITY_HEADERS.items())
    tmp = temp_dir
    # Loopback only: never a network-wide [::] listener (LAN exposure stays the IPv4 bind + firewall rule).
    v6 = f'\n        listen [::1]:{https_port} ssl;' if ipv6_loopback else ''
    return f"""# Generated by gtrade-ctl. Do not edit: changes are overwritten on repair and update.
worker_processes  1;
error_log  {_q(logs_dir / 'error.log')} warn;
pid        {_q(logs_dir / 'nginx.pid')};

events {{
    worker_connections  1024;
}}

http {{
    include       mime.types;
    default_type  application/octet-stream;
    server_tokens off;
    sendfile      on;
    keepalive_timeout  65;
    access_log  {_q(logs_dir / 'access.log')};
    client_body_temp_path {_q(tmp / 'client_body')};
    proxy_temp_path       {_q(tmp / 'proxy')};
    fastcgi_temp_path     {_q(tmp / 'fastcgi')};
    uwsgi_temp_path       {_q(tmp / 'uwsgi')};
    scgi_temp_path        {_q(tmp / 'scgi')};

    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml;
    client_max_body_size {max_body_mb}m;

    upstream gtrade_app {{
        server 127.0.0.1:{app_port};
        keepalive 16;
    }}

    server {{
        listen {listen_host}:{https_port} ssl;{v6}
        http2 on;
        server_name _;

        ssl_certificate      {_q(tls_dir / 'server.crt')};
        ssl_certificate_key  {_q(tls_dir / 'server.key')};
        ssl_protocols        TLSv1.2 TLSv1.3;
        ssl_prefer_server_ciphers off;
        ssl_session_cache    shared:SSL:5m;
        ssl_session_timeout  1d;

{headers}

        root {_q(spa_root)};
        index index.html;

        location = /index.html {{
            add_header Cache-Control "no-cache" always;
{headers.replace('    add_header', '            add_header')}
        }}
        location /assets/ {{
            expires 1y;
            add_header Cache-Control "public, immutable" always;
{headers.replace('    add_header', '            add_header')}
        }}
        # Public installation CA, for pairing workstations (authenticated by the pairing code).
        location = /gtrade-ca.crt {{
            alias {_q(tls_dir / 'ca.crt')};
            default_type application/x-x509-ca-cert;
            add_header Cache-Control "no-store" always;
        }}
        location /static/ {{
            alias {_q(str(static_root).rstrip('/\\\\') + '/')};
            expires 7d;
        }}
        location ~ ^/(api|admin|media)/ {{
            proxy_pass http://gtrade_app;
            proxy_http_version 1.1;
            proxy_set_header Connection "";
            proxy_set_header Host $http_host;
            proxy_set_header X-Forwarded-For $remote_addr;
            proxy_set_header X-Forwarded-Proto https;
            proxy_set_header X-Forwarded-Host $http_host;
            proxy_read_timeout 300s;
            proxy_send_timeout 300s;
        }}
        location / {{
            try_files $uri /index.html;
        }}
    }}
}}
"""


def write(layout, cfg, spa_root: Path) -> Path:
    import shutil
    for d in ('client_body', 'proxy', 'fastcgi', 'uwsgi', 'scgi'):
        (layout.temp_dir / 'nginx' / d).mkdir(parents=True, exist_ok=True)
    # Writable nginx prefix (see services.web_service_xml) and mime.types next to nginx.conf,
    # because `include mime.types` resolves relative to the config file's folder.
    for d in ('logs', 'temp'):
        (layout.run_dir / 'nginx' / d).mkdir(parents=True, exist_ok=True)
    mime_src = layout.nginx_dir / 'conf' / 'mime.types'
    if mime_src.exists():
        shutil.copy2(mime_src, layout.config_dir / 'mime.types')
    text = render(listen_host=cfg.bind_address, https_port=cfg.https_port, app_port=cfg.app_port,
                  spa_root=spa_root, static_root=layout.static_dir, tls_dir=layout.tls_dir,
                  logs_dir=layout.logs_dir / 'web', temp_dir=layout.temp_dir / 'nginx',
                  ipv6_loopback=ipv6_loopback_available())
    (layout.logs_dir / 'web').mkdir(parents=True, exist_ok=True)
    layout.nginx_conf.write_text(text, encoding='utf-8')
    return layout.nginx_conf
